#!/bin/sh
# xprs.dev/in/: refresh the portal page, its logo font and Reticulum for the
# browser from the sibling repos (portal/dist, portal/page/logo-font.css,
# reticulum-dart/build/rns.js). The portal page is
# the same file every station serves: never edit in/portal.html by hand.
set -e
HERE="$(cd "$(dirname "$0")/.." && pwd)"
cp "$HERE/../portal/dist/chat_page.html" "$HERE/in/portal.html"
cp "$HERE/../reticulum-dart/build/rns.js" "$HERE/in/rns.js"
# The logo font the looking page (404.html) shares with the portal.
cp "$HERE/../portal/page/logo-font.css" "$HERE/in/logo-font.css"
# The portal's keys, seals and NOSTR signer for the map (in/index.html signs
# in and sends direct messages with them): the same files the portal build
# splices in, the crypto's node test block cut as tool/build.py cuts it.
PAGE="$HERE/../portal/page"
{
  echo "/* GENERATED by tool/sync_in.sh from portal/page/xprs_crypto.js, xprs_seal.js and xprs_nostr.js: edit those, not this. */"
  sed '/^\/\/ ---- node test against the spec 9.1.2 worked example ----/,$d' "$PAGE/xprs_crypto.js"
  cat "$PAGE/xprs_seal.js" "$PAGE/xprs_nostr.js"
} > "$HERE/in/xprs.js"
ls -l "$HERE/in/portal.html" "$HERE/in/rns.js" "$HERE/in/xprs.js"
